import assert from "node:assert/strict";
import { Buffer, matches, labelMatches } from "../../mods/vim-copy/buffer.js";
const row = text => [...text].map((text, col) => ({ text, col, width: 1 }));
const b = new Buffer([row("alpha bravo"), row("charlie delta"), []]);
b.move("w"); assert.equal(b.column(), 6);
b.select(); b.move("e"); assert.equal(b.text(), "bravo");
b.move("b"); assert.equal(b.column(), 6);
b.move("b"); assert.equal(b.column(), 0);
assert.equal(b.text(), "alpha b");
b.clear(); b.select(true); b.move("j"); assert.equal(b.text(), "alpha bravo\ncharlie delta\n");
b.clear(); b.place(0, 10); b.move("j"); assert.equal(b.column(), 10); b.move("j"); b.move("k"); assert.equal(b.column(), 10);
const c = new Buffer([[{ text: "界", col: 0, width: 2 }, { text: "a", col: 2, width: 1 }]]);
const hit = matches(new Map([["a", b], ["b", c]]), "a");
assert(hit.some(m => m.pane === "b" && m.col === 2));
assert.equal(matches(new Map([["a", b]]), "ALPHA").length, 0);
const found = Array.from({ length: 1000 }, (_, i) => ({ pane: String(i), continuation: "a" }));
const labels = labelMatches(found);
assert.equal(new Set(labels.map(m => m.label)).size, 1000);
assert(labels.every(m => !m.label.includes("a") && m.label.length === labels[0].label.length));
c.select(); c.move("l"); assert.equal(c.text(), "界a");
const live = new Buffer([row("hello")]);
live.place(0, 1); live.select(); live.place(0, 3);
assert(live.update([row("WORLD")]));
assert.equal(live.text(), "ORL");
assert.deepEqual(live.spans(), [{ row: 0, col: 1, width: 3 }]);
assert.equal(live.update([row("WORLD")]), false);
live.update([[]]); assert.equal(live.text(), "");
console.log("PASS: word motions, forward/reverse/line selection, vertical column, Unicode columns, smartcase, global labels");
